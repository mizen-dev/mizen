import { readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { parseForESLint } from "@babel/eslint-parser";

const appRoot = fileURLToPath(
	new URL("../src/entities/documentation/ui/", import.meta.url)
);

function readRegistry(path, name) {
	const code = readFileSync(path, "utf8");
	const { ast } = parseForESLint(code, {
		babelOptions: {
			babelrc: false,
			configFile: false,
			parserOpts: { plugins: ["typescript", "jsx"] },
		},
		requireConfigFile: false,
	});
	const imports = new Map();
	for (const node of ast.body.filter(
		(item) =>
			item.type === "ImportDeclaration" && item.source.value.startsWith(".")
	)) {
		const source = `./${relative(
			appRoot,
			resolve(dirname(path), node.source.value)
		)
			.split(sep)
			.join("/")}`;
		for (const specifier of node.specifiers) {
			imports.set(specifier.local.name, {
				name: specifier.imported.name,
				source,
			});
		}
	}
	const declaration = ast.body
		.flatMap((node) => node.declaration?.declarations ?? [])
		.find((node) => node.id.name === name);
	return declaration.init.properties.map((property) => {
		const key = property.key.name ?? property.key.value;
		const imported = imports.get(property.value.name);
		return `${JSON.stringify(key)}: preloadableExample(() => import(${JSON.stringify(imported.source)}).then((module) => ({ default: module.${imported.name} }))),`;
	});
}

const usage = readRegistry(
	resolve(appRoot, "examples/index.ts"),
	"usageComponents"
);
const specimens = readRegistry(
	resolve(appRoot, "specimens/index.ts"),
	"specimenRegistry"
);
const output = `// Generated by scripts/sync-example-components.mjs.\nimport { preloadableExample } from "../../../shared/lib/preloadable-example";\n\nexport const usageComponents: Record<string, ReturnType<typeof preloadableExample>> = {\n${usage.join("\n")}\n};\n\nconst specimens: Record<string, ReturnType<typeof preloadableExample>> = {\n${specimens.join("\n")}\n};\n\nexport function getSpecimen(slug: string) { return specimens[slug]; }\n`;
writeFileSync(resolve(appRoot, "example-components.gen.ts"), output);
